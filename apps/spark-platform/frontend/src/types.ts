export type Observation = {
  source: string;
  entity: string;
  name: string;
  value: unknown;
  unit: string;
  status: string;
  reason: string | null;
  observed_at: string;
  window_seconds?: number | null;
};
export type Session = {
  id: string;
  dnn: string | null;
  address: string | null;
  sst: number | null;
  sd: string | null;
  five_qi: number | null;
  qfi?: number | null;
  pool_valid?: boolean;
  qos_flows?: { qfi: number; five_qi: number }[];
  ue_activity?: string;
  n3_verified?: boolean;
  state: string;
  status: string;
  source: string;
  observed_at: string;
};
export type Device = {
  id: string;
  stack: string;
  identity: string;
  identifiers: Record<string, unknown>;
  registration: string;
  state: string;
  status: string;
  source: string;
  correlation?: string;
  first_seen: string;
  observed_at: string;
  sessions: Session[];
  metrics: Observation[];
  connection?: {state: string; reason: string; layers: Record<string, string>};
  reachability?: {state: string; reason: string; observed_at: string; address?: string};
};
export type Component = {
  id: string;
  stack: string;
  name: string;
  kind: string;
  state: string;
  health?: string;
  business_health?: string;
  status?: string;
  details: Record<string, unknown>;
  observed_at: string;
  metrics: Observation[];
};
export type Service = {
  stack: string;
  name: string;
  role: string;
  state: string;
  health: string;
  status: string;
  exit_code: number | null;
  restarts: number | null;
};
export type Snapshot = {
  schema_version: number;
  observed_at: string;
  collector_status: string;
  active_stack: string;
  last_active_stack?: string;
  observations: Observation[];
  services: Service[];
  components?: Component[];
  links?: Component[];
  devices?: Device[];
  health?: Record<string, Record<string, string>>;
};
export type MonitoringEvent = {
  id: string;
  at: string;
  stack: string;
  entity?: string;
  level?: string;
  kind: string;
  message: string;
};
export type MetricPoint = { at: string; metrics: Observation[] };
export type ControlTask = {
  id: string;
  action: "start" | "stop" | "restart";
  state: string;
  current_step: string | null;
  steps: {name: string; state: string; at: number}[];
  error: string | null;
  created_at: string;
  updated_at: string;
};
